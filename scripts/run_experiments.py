"""Run the recommender, classification, and clustering experiments.

All outputs are computed from the reproducible SYNTHETIC dataset and are
illustrative only; they say nothing about real shopper behaviour.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Allow the documented `python scripts/run_experiments.py` invocation to import src.
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from src.classification import compare_classifiers, make_classification_dataset
from src.clustering import cluster_silhouette, fit_user_clusters, summarize_clusters
from src.config import RANDOM_SEED, RESULTS_DIR, TOP_K
from src.data_generation import generate_dataset
from src.evaluation import evaluate_recommenders

N_CLUSTERS = 3
DATA_SOURCE = (
    "Synthetic data generated by src/data_generation.py from the given seed "
    "(120 products, 80 users, 1,200 interactions); not real customer data."
)
CLASSIFICATION_TARGET = (
    "Proxy engagement label: 1 = wishlist/cart/purchase, 0 = view. "
    "Not purchase intent."
)
EVALUATION_PROTOCOL = (
    "Simulated-time leave-one-out: each eligible user's latest positive "
    "interaction is held out; both methods use the same users, K, and "
    "training history; already-seen items are excluded."
)

# Reference categorical palette slots 1 and 2 (blue, orange), light surface.
_BLUE, _ORANGE = "#2a78d6", "#eb6834"
_INK, _MUTED = "#0b0b0b", "#52514e"


def _style(ax) -> None:
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color("#c9c8c4")
    ax.tick_params(colors=_MUTED, length=0)
    ax.yaxis.grid(True, color="#ecebe8", linewidth=0.8)
    ax.set_axisbelow(True)


def _grouped_bars(ax, labels, series, colors, names) -> None:
    width = 0.38
    for i, (values, color, name) in enumerate(zip(series, colors, names)):
        positions = [x + (i - 0.5) * width for x in range(len(labels))]
        bars = ax.bar(positions, values, width=width - 0.04, color=color, label=name)
        for bar, value in zip(bars, values):
            ax.annotate(
                f"{value:.2f}",
                (bar.get_x() + bar.get_width() / 2, bar.get_height()),
                ha="center", va="bottom", fontsize=8, color=_INK,
                xytext=(0, 2), textcoords="offset points",
            )
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, color=_INK, fontsize=9)
    ax.set_ylim(0, 1.1)
    ax.set_ylim(0, 1.18)
    ax.legend(frameon=False, labelcolor=_INK, loc="upper left", ncols=2)
    _style(ax)


def _chart_recommenders(table: pd.DataFrame, k: int, seed: int, path: Path) -> None:
    metrics = [
        ("precision_at_k", f"Precision@{k}"),
        ("recall_at_k", f"Recall@{k}"),
        ("catalog_coverage", "Catalog coverage"),
        ("new_item_exposure", "New-item exposure"),
        ("relevant_new_item_rate", "Relevant new items\nsurfaced"),
    ]
    fig, ax = plt.subplots(figsize=(9, 4.6))
    by_method = table.set_index("method")
    _grouped_bars(
        ax,
        [label for _, label in metrics],
        [[by_method.loc[m, col] for col, _ in metrics] for m in ("baseline", "proposed")],
        (_BLUE, _ORANGE),
        ("Baseline (popularity)", "Proposed (cold-start-aware)"),
    )
    ax.set_title("Baseline vs proposed recommender", loc="left", color=_INK, fontsize=12)
    fig.text(0.01, 0.01, f"Synthetic data, seed={seed}, K={k}. Illustrative only.",
             fontsize=8, color=_MUTED)
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    fig.savefig(path, dpi=150)
    plt.close(fig)


def _chart_classifiers(table: pd.DataFrame, seed: int, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(9, 4.6))
    _grouped_bars(
        ax,
        list(table["classifier"]),
        [list(table["accuracy"]), list(table["f1"])],
        (_BLUE, _ORANGE),
        ("Accuracy", "F1"),
    )
    ax.set_title("Classifier comparison (proxy engagement label)", loc="left",
                 color=_INK, fontsize=12)
    fig.text(0.01, 0.01, f"Synthetic data, seed={seed}, 75/25 stratified holdout. "
             "Target is a proxy, not purchase intent.", fontsize=8, color=_MUTED)
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    fig.savefig(path, dpi=150)
    plt.close(fig)


def run_experiments(
    seed: int = RANDOM_SEED,
    output_dir: str | Path = RESULTS_DIR,
    top_k: int = TOP_K,
) -> dict[str, pd.DataFrame]:
    """Run all experiments and write tables, charts, and metadata."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    data = generate_dataset(seed=seed)
    products, users, interactions = data["products"], data["users"], data["interactions"]

    recommender = evaluate_recommenders(products, users, interactions, top_k=top_k)
    recommender.insert(0, "seed", seed)

    features, labels = make_classification_dataset(users, products, interactions)
    classifiers = compare_classifiers(features, labels, seed=seed)
    classifiers.insert(0, "seed", seed)

    model = fit_user_clusters(users, n_clusters=N_CLUSTERS, seed=seed)
    summary = summarize_clusters(users, model.labels_)
    silhouette = cluster_silhouette(users, model)

    recommender.to_csv(out / "recommender_comparison.csv", index=False)
    classifiers.to_csv(out / "classifier_comparison.csv", index=False)
    summary.to_csv(out / "cluster_summary.csv", index=False)
    _chart_recommenders(recommender, top_k, seed, out / "recommender_comparison.png")
    _chart_classifiers(classifiers, seed, out / "classifier_comparison.png")

    metadata = {
        "seed": seed,
        "top_k": top_k,
        "n_clusters": N_CLUSTERS,
        "silhouette_score": silhouette,
        "n_products": len(products),
        "n_users": len(users),
        "n_interactions": len(interactions),
        "data_source": DATA_SOURCE,
        "classification_target": CLASSIFICATION_TARGET,
        "evaluation_protocol": EVALUATION_PROTOCOL,
        "deep_learning": "Not included (optional, deferred).",
    }
    (out / "experiment_metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    return {
        "recommender_comparison": recommender,
        "classifier_comparison": classifiers,
        "cluster_summary": summary,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Run experiments on synthetic data.")
    parser.add_argument("--seed", type=int, default=RANDOM_SEED)
    parser.add_argument("--output-dir", default=str(RESULTS_DIR))
    parser.add_argument("--top-k", type=int, default=TOP_K)
    args = parser.parse_args()

    results = run_experiments(args.seed, args.output_dir, args.top_k)
    print(f"Synthetic-data experiments (seed={args.seed}, K={args.top_k})")
    for name, table in results.items():
        print(f"\n{name}:\n{table.to_string(index=False)}")
    print(f"\nOutputs written to {args.output_dir}")


if __name__ == "__main__":
    main()
